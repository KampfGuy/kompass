// Generates docs/KAMPFSCRIPT_FOR_AI.md (+ resources/KAMPFSCRIPT_FOR_AI.md for kompass://learn/ai)
// from the REAL interpreter and host. Examples are executed and their real output embedded.
// Usage: node tools/gen-ai-doc.js [--check]
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const K = require(path.join(ROOT, 'src', 'lang.js'));
const DOCS = require('./builtin-docs.js');

function realBuiltins() {
  const core = [...new K.Interpreter().globals.vars.keys()];
  const host = fs.readFileSync(path.join(ROOT, 'src', 'host.js'), 'utf8').split('\n');
  const groups = { ui: [], tabs: [], services: [], page: [] }; let g = null, inPage = false;
  for (const l of host) {
    if (/^\s{4}const ui = \{/.test(l)) g = 'ui'; else if (/^\s{4}const browser = \{/.test(l)) g = 'tabs'; else if (/^\s{4}const services = \{/.test(l)) g = 'services'; else if (/^\s{4}\};/.test(l)) g = null;
    if (/^\s{6}run_page: B\(/.test(l)) inPage = true;
    if (inPage && /^\s{8}\};/.test(l)) inPage = false;
    let m;
    if (g && (m = l.match(/^\s{6}([a-z_]+): B\(/))) groups[g].push(m[1]);
    if (inPage && (m = l.match(/^\s{10}([a-z_]+): B\(/)) && !core.includes(m[1])) groups.page.push(m[1]);
  }
  groups.ui = groups.ui.filter(n => !core.includes(n));
  groups.editor = [...fs.readFileSync(path.join(ROOT, 'src', 'editor.js'), 'utf8').matchAll(/^\s{8}([a-z_]+): \{ fn:/gm)].map(m => m[1]);  // print is also a host override
  return { core, ...groups };
}

