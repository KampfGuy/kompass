module.exports = { build, realBuiltins };
if (require.main === module) {
  build().then((md) => {
    const outs = [path.join(ROOT, 'docs', 'KAMPFSCRIPT_FOR_AI.md'), path.join(ROOT, 'resources', 'KAMPFSCRIPT_FOR_AI.md')];
    if (process.argv.includes('--check')) { for (const f of outs) if (!fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== md) { console.error('out of date: ' + f + ' (run node tools/gen-ai-doc.js)'); process.exit(1); } console.log('AI doc up to date'); return; }
    for (const f of outs) fs.writeFileSync(f, md);
    console.log('wrote', outs.join(', '), md.split('\n').length, 'lines');
  }).catch((e) => { console.error(e.message); process.exit(1); });
}
