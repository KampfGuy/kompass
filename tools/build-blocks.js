#!/usr/bin/env node
// Builds the Kugel Blocks store apps from kugel-apps/blocks/*.ks:
//   kugel-blocks.ks     = 2D (Scratch-style) editor + 2D game runtime
//   kugel-blocks-3d.ks  = 3D editor + 3D game runtime
// The game runtime is embedded as a string (RUNTIME_SRC): the green flag runs runtime + compiled blocks with run_app(),
// and "Export game" writes the same text to a .ks file.
// Usage: node tools/build-blocks.js [outDir]   (default: kugel-apps/dist)
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'kugel-apps', 'blocks');
const out = path.resolve(process.argv[2] || path.join(__dirname, '..', 'kugel-apps', 'dist'));
const rd = (f) => fs.readFileSync(path.join(dir, f), 'utf8');
const q = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r/g, '').replace(/\n/g, '\\n') + '"';
const VARIANTS = {
  'kugel-blocks.ks': {
    title: 'Kugel Blocks — make 2D games with blocks (Scratch-style). Blocks compile to KampfScript.',
    runtime: ['runtime-core.ks', 'runtime2d.ks'], parts: ['spec-common.ks', 'spec2d.ks', 'editor.ks', 'samples-common.ks', 'target2d.ks', 'samples2d.ks', 'start.ks'],
  },
  'kugel-blocks-3d.ks': {
    title: 'Kugel Blocks 3D — make 3D games with blocks. Blocks compile to KampfScript.',
    runtime: ['runtime-core.ks', 'runtime3d.ks'], parts: ['spec-common.ks', 'spec3d.ks', 'editor.ks', 'samples-common.ks', 'target3d.ks', 'samples3d.ks', 'start.ks'],
  },
};
function build(name) {
  const v = VARIANTS[name];
  for (const f of v.runtime.concat(v.parts)) if (!fs.existsSync(path.join(dir, f))) return null;
  const runtime = v.runtime.map(rd).join('\n');
  const src = [
    '# ============================================================================',
    '#  ' + v.title,
    '#  Kugel Store app for Kompass 1.7+. Generated by tools/build-blocks.js from kugel-apps/blocks/ — edit those files.',
    '# ============================================================================',
    'let RUNTIME_SRC = ' + q(runtime),
    ...v.parts.map((f) => '\n# ======== ' + f + '\n' + rd(f)),
  ].join('\n');
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, name), src);
  return { name, bytes: src.length, runtimeBytes: runtime.length };
}
if (require.main === module) {
  for (const n of Object.keys(VARIANTS)) { const r = build(n); console.log(r ? `${r.name}: ${(r.bytes / 1024).toFixed(1)} KB (runtime ${(r.runtimeBytes / 1024).toFixed(1)} KB)` : `${n}: skipped (missing parts)`); }
}
module.exports = { build, VARIANTS };
