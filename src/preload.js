// Narrow, safe bridge between the KampfScript runtime (renderer) and the main process.
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('native', {
  browserSource: () => ipcRenderer.sendSync('kompass:browser-source'),
  defaultSource: () => ipcRenderer.sendSync('kompass:default-source'),
  saveBrowserSource: (s) => ipcRenderer.sendSync('kompass:save-browser-source', s),
  paths: () => ipcRenderer.sendSync('kompass:paths'),
  load: (n) => ipcRenderer.sendSync('kompass:load', n),
  save: (n, j) => ipcRenderer.sendSync('kompass:save', n, j),
  listScripts: () => ipcRenderer.sendSync('kompass:list-scripts'),
  readScript: (n) => ipcRenderer.sendSync('kompass:read-script', n),
  writeScript: (n, s) => ipcRenderer.sendSync('kompass:write-script', n, s),
  adblock: (on) => ipcRenderer.sendSync('kompass:adblock', on === undefined ? null : on),
  openExternal: (u) => ipcRenderer.send('kompass:open-external', u),
  openFolder: () => ipcRenderer.send('kompass:open-folder'),
  reloadApp: () => ipcRenderer.send('kompass:reload-app'),
  devtools: () => ipcRenderer.send('kompass:devtools'),
  capture: (f) => ipcRenderer.invoke('kompass:capture', f),
  argv: () => ipcRenderer.sendSync('kompass:argv'),
  quit: () => ipcRenderer.send('kompass:quit'),
  version: () => ipcRenderer.sendSync('kompass:version'),
  clearBrowsingData: () => ipcRenderer.invoke('kompass:clear-data'),
  videoFile: (n) => ipcRenderer.sendSync('kompass:video-file', n),
  videosFolder: () => ipcRenderer.sendSync('kompass:videos-folder'),
  openVideosFolder: () => ipcRenderer.send('kompass:open-videos-folder'),
  readResource: (n) => ipcRenderer.sendSync('kompass:read-resource', n),
  copyText: (t) => ipcRenderer.sendSync('kompass:copy-text', t),
  saveTextFile: (n, t) => ipcRenderer.invoke('kompass:save-text-file', n, t),
  pw: {
    status: () => ipcRenderer.sendSync('kompass:pw-status'),
    unlock: (m) => ipcRenderer.sendSync('kompass:pw-unlock', m),
    lock: () => ipcRenderer.sendSync('kompass:pw-lock'),
    list: (q) => ipcRenderer.sendSync('kompass:pw-list', q),
    save: (id, o, u, p) => ipcRenderer.sendSync('kompass:pw-save', id, o, u, p),
    remove: (id) => ipcRenderer.sendSync('kompass:pw-delete', id),
    reveal: (id) => ipcRenderer.sendSync('kompass:pw-reveal', id),
    copy: (id) => ipcRenderer.sendSync('kompass:pw-copy', id),
    generate: (n) => ipcRenderer.sendSync('kompass:pw-generate', n),
    offer: (id, a) => ipcRenderer.sendSync('kompass:pw-offer', id, a),
    exportTo: (k, p) => ipcRenderer.invoke('kompass:pw-export', k, p),
    importFrom: (p) => ipcRenderer.invoke('kompass:pw-import', p),
    onOffer: (f) => ipcRenderer.on('kompass:pw-offer', (_e, o) => f(o)),
    onLocked: (f) => ipcRenderer.on('kompass:pw-locked', () => f()),
  },
  update: {
    state: () => ipcRenderer.sendSync('kompass:update-state'),
    check: () => ipcRenderer.invoke('kompass:update-check'),
    auto: (on) => ipcRenderer.sendSync('kompass:update-auto', on),
    install: () => ipcRenderer.sendSync('kompass:update-install'),
    onState: (f) => ipcRenderer.on('kompass:update-state', (_e, s) => f(s)),
  },
  onDoubleRight: (f) => ipcRenderer.on('kompass:double-right', (_e, p) => f(p)),
  onOpenTab: (f) => ipcRenderer.on('kompass:open-tab', (_e, u) => f(u)),
  onKey: (f) => ipcRenderer.on('kompass:key', (_e, k) => f(k)),
});
